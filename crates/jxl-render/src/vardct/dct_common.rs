pub fn sec_half(n: usize) -> &'static [f32] {
    assert!(n.is_power_of_two() && (4..=256).contains(&n));
    let idx = n.trailing_zeros() as usize - 2;
    if idx < SEC_HALF_SMALL.len() {
        SEC_HALF_SMALL[idx]
    } else {
        SEC_HALF_LARGE[idx - SEC_HALF_SMALL.len()]
    }
}

pub const fn sec_half_small(n: usize) -> &'static [f32] {
    let idx = n.trailing_zeros() as usize - 2;
    SEC_HALF_SMALL[idx]
}

